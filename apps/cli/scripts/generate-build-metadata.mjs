import { readFile, writeFile } from "node:fs/promises";
import { fileURLToPath } from "node:url";

const manifestPath = fileURLToPath(new URL("../package.json", import.meta.url));
const outputPath = fileURLToPath(
  new URL("../src/generated-build-metadata.ts", import.meta.url),
);

const manifest = JSON.parse(await readFile(manifestPath, "utf8"));
if (
  typeof manifest.version !== "string" ||
  !/^[0-9]+\.[0-9]+\.[0-9]+(?:-[0-9A-Za-z.-]+)?(?:\+[0-9A-Za-z.-]+)?$/u.test(
    manifest.version,
  )
) {
  throw new Error("apps/cli/package.json must contain a valid package version.");
}

const generatedSource = `// Generated by scripts/generate-build-metadata.mjs. Do not edit.

export const GENERATED_BUILD_METADATA = Object.freeze({
  schemaVersion: 1,
  version: ${JSON.stringify(manifest.version)},
  buildId: "development",
  channel: "development",
} as const);
`;

const args = process.argv.slice(2);
if (
  args.length > 1 ||
  (args.length === 1 && !["--check", "--print"].includes(args[0]))
) {
  throw new Error("Usage: generate-build-metadata.mjs [--check|--print]");
}

if (args[0] === "--print") {
  process.stdout.write(generatedSource);
} else if (args[0] === "--check") {
  let currentSource = "";
  try {
    currentSource = await readFile(outputPath, "utf8");
  } catch (error) {
    if (!isMissingFile(error)) throw error;
  }
  if (currentSource !== generatedSource) {
    throw new Error(
      "Generated CLI build metadata is stale; run npm run generate:build-metadata --workspace @zachshotamartin/robin.",
    );
  }
} else {
  let currentSource = "";
  try {
    currentSource = await readFile(outputPath, "utf8");
  } catch (error) {
    if (!isMissingFile(error)) throw error;
  }
  if (currentSource !== generatedSource) {
    await writeFile(outputPath, generatedSource, "utf8");
  }
}

function isMissingFile(error) {
  return (
    typeof error === "object" &&
    error !== null &&
    "code" in error &&
    error.code === "ENOENT"
  );
}
